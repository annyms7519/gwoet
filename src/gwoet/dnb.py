def discrete_naive_bayes(
    X,
    y,
    weight=None,
    discretizer='bic',
    cross_fitting=False,
    n_splits=5,
    shuffle=True,
    random_state=None,
):
    """
    Generate a discrete naive Bayes model from training data.

    Args:
      X:
        DataFrame containing numerical or categorical variables.
      y:
        One-dimensional array-like target variable with the same number
        of observations as X.
      weight:
        Optional one-dimensional array-like object containing non-negative
        sample weights. It must have the same number of observations as X.
        If None, all sample weights are set to 1.0.
      discretizer:
        Discretization method. Must be "bic" or "mdlp".
      cross_fitting:
        Whether to use cross-fitted Weight of Evidence (WoE) values for
        the training data. If True, each observation is transformed using
        WoE values estimated without using the fold containing that
        observation.
      n_splits:
        Number of folds used for cross-fitting. Must be at least 2.
        This argument is used only when cross_fitting is True.
      shuffle:
        Whether to shuffle the observations before constructing the
        cross-fitting folds. This argument is used only when cross_fitting
        is True.
      random_state:
        Random seed used when constructing shuffled cross-fitting folds.
        This argument is effective only when both cross_fitting and shuffle
        are True.

    Returns:
      Dict containing the following keys:
        disc:
          Dictionary of discretizers generated by generate_disc.
        train:
          Trained discrete naive Bayes model generated by
          discrete_naive_bayes_main.
    """
    if not isinstance(X, pd.DataFrame):
        raise TypeError("X must be a DataFrame.")

    if not isinstance(cross_fitting, bool):
        raise TypeError("cross_fitting must be a boolean.")

    if not isinstance(n_splits, int) or isinstance(n_splits, bool):
        raise TypeError("n_splits must be an integer.")

    if n_splits < 2:
        raise ValueError("n_splits must be at least 2.")

    if not isinstance(shuffle, bool):
        raise TypeError("shuffle must be a boolean.")

    if (
        random_state is not None
        and (
            not isinstance(random_state, int)
            or isinstance(random_state, bool)
        )
    ):
        raise TypeError("random_state must be an integer or None.")

    disc = generate_disc(
        X,
        y,
        weight=weight,
        discretizer=discretizer,
    )

    X_d = apply_disc(
        disc,
        X,
    )

    train = discrete_naive_bayes_main(
        X_d,
        y,
        weight=weight,
        cross_fitting=cross_fitting,
        n_splits=n_splits,
        shuffle=shuffle,
        random_state=random_state,
        )

    model = {
        'disc': disc,
        'train': train,
    }

    return model

def discrete_naive_bayes_main(
    X,
    y,
    weight=None,
    cross_fitting=False,
    n_splits=5,
    shuffle=True,
    random_state=None,
):
    """
    Main function for training a discrete naive Bayes model.

    Args:
      X:
        DataFrame containing categorical variables.
        Numerical variables must be discretized beforehand.
      y:
        Binary target variable. ndarray, Series, or list.
      weight:
        Optional one-dimensional ndarray of sample weights.
        If None, all sample weights are set to 1.0.
        Negative values are clipped to 0.0.
      cross_fitting:
        Whether to use cross-fitted WoE values for the training data.
        If True, each observation is transformed using WoE values
        estimated without that observation's fold.
      n_splits:
        Number of folds used for cross-fitting.
        This argument is used only when cross_fitting=True.
      shuffle:
        Whether to shuffle observations before constructing the folds.
        This argument is used only when cross_fitting=True.
      random_state:
        Random seed used for fold construction when shuffle=True.
        This argument is used only when cross_fitting=True.

    Returns:
      Dict with the following keys:
        y_bool:
          Boolean Series representing the positive class.
        count:
          Dict containing category counts estimated from the full training data.
        woe:
          Dict containing WoE values estimated from the full training data.
          These values are used when transforming validation, test, or new data.
        woe_table:
          DataFrame containing WoE-transformed training variables.
          If cross_fitting=False, the WoE values are estimated from the full training data.
          If cross_fitting=True, cross-fitted WoE values are returned.
        fold:
          Series containing the validation-fold number assigned to each observation,
          if cross_fitting=True.
        raw_score:
          Sum of WoE values for each observation, if logi=True.
        probability:
          Probability estimates calculated as 1 / (1 + exp(-(c0 + c1 * raw_score))),
          if logi=True.
        c0:
          Logistic calibration intercept, if logi=True.
        c1:
          Logistic calibration coefficient, if logi=True.
        iter:
          Number of logistic calibration iterations, if logi=True.
    """
    y_bool = make_y_bool(
        y,
        index=X.index,
    )

    weight_array = make_sample_weight(
        weight,
        len(X),
    )

    if cross_fitting:
        woe_result = _calculate_cross_fitted_woe_main(
            X,
            y_bool,
            weight_array,
            n_splits=n_splits,
            shuffle=shuffle,
            random_state=random_state,
            laplace=LAPLACE,
        )
    else:
        woe_result = _calculate_woe_main_fast(
            X,
            y_bool,
            weight_array,
            LAPLACE,
        )

    raw_score = (
        woe_result["woe_table"]
        .sum(axis=1)
        .to_numpy(dtype=float)
    )

    logistic_result = _logistic_regression(
        raw_score,
        y_bool,
        weight_array,
    )

    return {
        "y_bool": y_bool,
        **woe_result,
        **logistic_result,
    }

def is_discrete_naive_bayes(
    model,
):
    """
    Check whether a model is a discrete naive Bayes model.
    """
    return (
        isinstance(model, dict)
        and {'disc', 'train'} <= model.keys()
    )

def predict_dnb(
    model,
    X,
):
    """
    Make predictions using a discrete naive Bayes model.

    Args:
      model:
        Trained discrete naive Bayes model generated by
        discrete_naive_bayes().
      X:
        DataFrame containing numerical or categorical variables
        corresponding to the samples to be predicted.

    Returns:
      Dict containing the following keys:
        raw_score:
          Array containing the total Weight of Evidence scores.
        probability:
          Array containing calibrated probability estimates for the
          target class.
    """
    if not isinstance(model, dict):
        raise TypeError("model must be a dictionary.")

    if not is_discrete_naive_bayes(model):
        raise ValueError(
            "model must be a discrete naive Bayes model generated by "
            "discrete_naive_bayes()."
        )

    if not isinstance(X, pd.DataFrame):
        raise TypeError("X must be a pandas DataFrame.")

    variables = [
        var for var in X.columns
        if var in model["disc"]
    ]
    X = X[variables]

    train = model["train"]

    # Apply the discretization fitted on the training data.
    X_d = apply_disc(
        model["disc"],
        X,
    )

    # Apply the WoE mappings fitted on the training data.
    woe_table = apply_woe(
        X_d,
        train["woe"],
    )

