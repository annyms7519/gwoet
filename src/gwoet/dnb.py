def plot_woe(
    model,
    variables=None,
):
    """
    Display Weight of Evidence (WoE) plots for variables.

    Args:
      model:
        Discrete naive Bayes model generated by discrete_naive_bayes().
      variables:
        List of variable names. If None, all variables are plotted.

    Returns:
      None.
    """
    if not isinstance(model, dict):
        raise TypeError("model must be a dictionary.")

    if not is_discrete_naive_bayes(model):
        raise ValueError(
            "model must be a discrete naive Bayes model generated by "
            "discrete_naive_bayes()."
        )

    if variables is not None and not isinstance(variables, list):
        raise TypeError("variables must be a list or None.")


    def plot_woe_main(
        model,
        var,
    ):
        disc = model["disc"]
        train = model["train"]
        y_bool = train["y_bool"]
        key_cnt = train["count"][var]
        woe = train["woe"][var]
        woe_vec = train["woe_table"][var]

        iv = float(
            np.mean(woe_vec[y_bool])
            - np.mean(woe_vec[~y_bool])
        )

        plot_data = pd.DataFrame({
            "category": [
                f"{cat} (N={key_cnt[cat]})"
                for cat in woe.keys()
            ],
            "woe": list(woe.values()),
        })

        fig, ax = plt.subplots(
            figsize=(7, max(3, 0.3 * len(plot_data)))
        )

        sns.barplot(
            data=plot_data,
            x="woe",
            y="category",
            orient="h",
            errorbar=None,
            ax=ax,
        )

        ax.axvline(
            0,
            linestyle="--",
            linewidth=1,
        )

        ax.set(
            title=f"{var}  (IV = {iv:.3f})",
            xlabel="Weight of Evidence (WoE)",
            ylabel=None,
        )

        sns.despine(
            ax=ax,
            left=True,
            bottom=True,
        )

        fig.tight_layout()
        plt.show()

        return iv


    if variables is None:
        all_variables = model['train']['woe'].keys()
        iv_list = [plot_woe_main(model, var) for var in all_variables]
        ivs = dict(zip(all_variables, iv_list))

    else:
        iv_list = [plot_woe_main(model, var) for var in variables]
        ivs = dict(zip(variables, iv_list))

    return ivs

"""
scikit-learn compliant class that provides methods for discrete naive Bayes.
"""
from sklearn.base import BaseEstimator, ClassifierMixin
from sklearn.utils.validation import check_is_fitted
from sklearn.exceptions import NotFittedError

class DiscreteNaiveBayes(BaseEstimator, ClassifierMixin):

    def __init__(
        self,
        discretizer='bic',
        cross_fitting=False,
        n_splits=5,
        shuffle=True,
        random_state=None,
    ):
        self.discretizer = discretizer
        self.cross_fitting = cross_fitting
        self.n_splits = n_splits
        self.shuffle = shuffle
        self.random_state = random_state

    def __sklearn_tags__(
        self,
    ):
        tags = super().__sklearn_tags__()
        tags.estimator_type = "classifier"
        tags.input_tags.allow_nan = True
        return tags

    def fit(
        self,
        X,
        y,
        weight=None,
    ):
        ycat = pd.Categorical(y)
        self.classes_ = np.array(ycat.categories)
        self.coef_ = discrete_naive_bayes(
            X,
            y,
            weight=weight,
            discretizer=self.discretizer,
            cross_fitting=self.cross_fitting,
            n_splits=self.n_splits,
            shuffle=self.shuffle,
            random_state=self.random_state,
        )
        return self

    def predict(
        self,
        X,
    ):
        try:
            check_is_fitted(self, attributes=['coef_', 'classes_'])
        except NotFittedError as exc:
            print(f"The model is not fitted yet.")

        pred = predict_dnb(self.coef_, X)
        return (pred['probability'] >= 0.5)

    def predict_proba(
        self,
        X,
    ):
        try:
            check_is_fitted(self, attributes=['coef_', 'classes_'])
        except NotFittedError as exc:
            print(f"The model is not fitted yet.")

        pred = predict_dnb(self.coef_, X)
        p = pred['probability']
        return np.stack([1 - p, p], 1)

    def score(
        self,
        X,
        y,
    ):
        try:
            check_is_fitted(self, attributes=['coef_', 'classes_'])
        except NotFittedError as exc:
            print(f"The model is not fitted yet.")

        return get_accuracy_score(
            self.coef_,
            X,
            y,
        )

    def get_iv(
        self,
        variables=None,
    ):
        try:
            check_is_fitted(self, attributes=['coef_', 'classes_'])
        except NotFittedError as exc:
            print(f"The model is not fitted yet.")

        return get_iv(
            self.coef_,
            variables,
        )

    def plot_iv(
        self,
        variables=None,
    ):
        try:
            check_is_fitted(self, attributes=['coef_', 'classes_'])
        except NotFittedError as exc:
            print(f"The model is not fitted yet.")

        iv = get_iv(
            self.coef_,
            variables=variables,
        )
        return plot_iv(iv)


    def plot_woe(
        self,
        variables=None,
    ):
        try:
            check_is_fitted(self, attributes=['coef_', 'classes_'])
        except NotFittedError as exc:
            print(f"The model is not fitted yet.")

        return plot_woe(
            self.coef_,
            variables
        )

    def get_model(
        self,
    ):
        try:
            check_is_fitted(self, attributes=['coef_', 'classes_'])
        except NotFittedError as exc:
            print(f"The model is not fitted yet.")

        return self.coef_

